// app/layout.tsx
import { Outfit } from "next/font/google";
import { Bounce, ToastContainer } from "react-toastify";
import { Providers } from "./providers";
import { getAllProducts, getCategories } from "./_lib/data-services";
import QueryProvider from "./_lib/providers/QueryProvider";
import { AppProvider } from "@/components/AppContext";
import "./globals.css";
import { CurrencyProvider } from "@/components/CurrencyContext";
import { NetworkProvider } from "@/components/NetworkContext";

const outfit = Outfit({
  subsets: ["latin"],
  variable: "--font-outfit",
  display: "swap",
});

export const metadata = {
  title: {
    template: "%s / Fourthview-Trading",
    default: "Welcome / Fourthview-Trading",
  },
  description: "Generated by create next app",
};

export default async function RootLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  const [products, categories] = await Promise.all([
    getAllProducts(),
    getCategories(),
  ]);

  return (
    <html lang="en">
      <body className={`${outfit.className} antialiased`}>
        <QueryProvider>
          <AppProvider products={products || []} categories={categories || []}>
            <NetworkProvider>
              <CurrencyProvider>
                <Providers>{children}</Providers>
              </CurrencyProvider>
            </NetworkProvider>

            <ToastContainer
              position="top-center"
              theme="dark"
              rtl={false}
              draggable
              pauseOnHover
              pauseOnFocusLoss
              transition={Bounce}
              hideProgressBar
              autoClose={5000}
              closeButton={false}
              className="flex items-center min-w-40 text-sm text-slate-500 rounded-2xl toast-container"
            />
          </AppProvider>
        </QueryProvider>
      </body>
    </html>
  );
}
